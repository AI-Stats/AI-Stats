import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { dump, load } from "js-yaml";

const REPOSITORY_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE_PATH = resolve(REPOSITORY_ROOT, "apps/docs/openapi/v1/openapi.yaml");
const OUTPUT_PATH = resolve(REPOSITORY_ROOT, "apps/docs/openapi/v1/openapi.public.yaml");
const CHECK_ONLY = process.argv.includes("--check");
const INTERNAL_PATHS = [
	/^\/videos(?:\/|$)/,
	/^\/video\/generations(?:\/|$)/,
	/^\/batches(?:\/|$)/,
	/^\/batch(?:\/|$)/,
];

function decodePointerSegment(value) {
	return value.replaceAll("~1", "/").replaceAll("~0", "~");
}

function componentReference(value) {
	if (typeof value !== "string") return null;
	const match = value.match(/^#\/components\/([^/]+)\/([^/]+)/);
	if (!match) return null;
	return [decodePointerSegment(match[1]), decodePointerSegment(match[2])];
}

function collectReferences(value, enqueue) {
	if (Array.isArray(value)) {
		for (const item of value) collectReferences(item, enqueue);
		return;
	}
	if (!value || typeof value !== "object") return;
	for (const [key, child] of Object.entries(value)) {
		if (key === "$ref") {
			const reference = componentReference(child);
			if (reference) enqueue(reference);
		} else {
			collectReferences(child, enqueue);
		}
	}
}

function publicComponents(document, sourceComponents) {
	const selected = {};
	const queued = [];
	const seen = new Set();
	const enqueue = ([group, name]) => {
		const key = `${group}/${name}`;
		if (seen.has(key)) return;
		seen.add(key);
		queued.push([group, name]);
	};

	collectReferences(document, enqueue);
	while (queued.length > 0) {
		const [group, name] = queued.shift();
		const component = sourceComponents?.[group]?.[name];
		if (component === undefined) continue;
		selected[group] ??= {};
		selected[group][name] = component;
		collectReferences(component, enqueue);
	}

	if (sourceComponents?.securitySchemes) {
		selected.securitySchemes = sourceComponents.securitySchemes;
	}
	return selected;
}

function buildPublicDocument(source) {
	const document = structuredClone(source);
	for (const path of Object.keys(document.paths ?? {})) {
		if (INTERNAL_PATHS.some((pattern) => pattern.test(path))) delete document.paths[path];
	}
	const sourceComponents = document.components;
	delete document.components;
	const components = publicComponents(document, sourceComponents);
	if (Object.keys(components).length > 0) document.components = components;
	return document;
}

const source = load(readFileSync(SOURCE_PATH, "utf8"));
const output = [
	"# Generated by scripts/openapi/build-public-docs-spec.mjs. Do not edit directly.",
	dump(buildPublicDocument(source), {
		lineWidth: 120,
		noRefs: true,
		noCompatMode: true,
	}),
].join("\n");

if (CHECK_ONLY) {
	const current = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, "utf8") : "";
	if (current !== output) {
		console.error("Public OpenAPI specification is stale. Run `pnpm docs:openapi`.");
		process.exitCode = 1;
	} else {
		console.log("Public OpenAPI specification is current.");
	}
} else {
	writeFileSync(OUTPUT_PATH, output, "utf8");
	console.log("Generated apps/docs/openapi/v1/openapi.public.yaml.");
}
